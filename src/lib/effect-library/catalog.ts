function fx(
  partial: Omit<CanonicalEffect, 'minVisualClues' | 'combinations'> & {
    minVisualClues?: number;
    combinations?: string[];
  }
): CanonicalEffect {
  return {
    minVisualClues: 3,
    combinations: [],
    ...partial,
  };
}

