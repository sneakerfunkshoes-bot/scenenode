export const EFFECT_LIBRARY: CanonicalEffect[] = [...CORE_LIBRARY, ...EXTRA_LIBRARY];

export function libraryById(id: string): CanonicalEffect | undefined {
  return EFFECT_LIBRARY.find((e) => e.id === id);
}

export function libraryPromptIndex(): string {
  const groups: Array<[string, CanonicalEffect['type']]> = [
    ['TRANSFORMS / MOTION', 'transform'],
    ['OVERLAYS', 'overlay'],
    ['TRANSITIONS', 'transition'],
    ['EFFECTS', 'effect'],
    ['COMPOUND RECIPES (prefer when 2+ layers)', 'compound'],
  ];
  return groups
    .map(([label, type]) => {
      const rows = EFFECT_LIBRARY.filter((e) => e.type === type)
        .map((e) => `${e.id} | ${e.canonicalName} aka ${e.aliases.join(', ')}`)
        .join('\n');
      return rows ? `### ${label}\n${rows}` : '';
    })
    .filter(Boolean)
    .join('\n\n');
}
